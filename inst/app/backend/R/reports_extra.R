reg_is_lin <- function(res) identical(res$spec$family, "gaussian")

reg_body_html <- function(res) {
  esc <- html_escape
  s <- res$spec
  lin <- reg_is_lin(res)
  ci <- paste0(round(100 * s$ciLevel), "% CI")
  S <- character(0); a <- function(...) S <<- c(S, paste0(...))
  a("<h2>Regression analysis</h2>")
  a("<p>", esc(res$familyLabel), " regression of <strong>", esc(s$outcome), "</strong> in ", length(res$blocks), " block(s) (n = ", res$n$used,
    if (res$n$rowsRemoved > 0) paste0("; ", res$n$rowsRemoved, " row(s) with missing values left out listwise") else "", "). ",
    if (s$robust != "none") paste0(esc(s$robust), " heteroscedasticity-consistent standard errors (sandwich ", esc(res$packages$sandwich), "). ") else "",
    if (length(res$centred)) paste0("Mean-centred for interactions: ", esc(paste(vapply(res$centred, `[[`, "", "variable"), collapse = ", ")), ". ") else "",
    if (!is.null(res$event)) paste0("Event (coded 1): ", esc(s$outcome), " = ", res$event$level, "; reference ", res$event$reference, ". ") else "",
    "Estimated with R's ", if (lin) "lm" else "glm", "().</p>")
  for (w in ul(res$warnings)) a("<div class=\"warn\">", esc(w), "</div>")
  summ_rows <- lapply(res$blocks, function(b) {
    sm <- b$summary; ch <- b$change
    if (lin) c(paste0(b$block, ": ", esc(paste(ul(b$added), collapse = ", "))), fmt(sm$r2), fmt(sm$adjR2), fmt(sm$deltaR2),
               paste0("F(", ch$df1, ", ", ch$df2, ") = ", fmt(ch$stat, 2)), flag(fmt_p(ch$p), gt(ch$p, 0.05 - 1e-12)), fmt(sm$aic, 2))
    else c(paste0(b$block, ": ", esc(paste(ul(b$added), collapse = ", "))), fmt(sm$mcfaddenR2), fmt(sm$nagelkerkeR2 %||% NA),
           paste0("&chi;&sup2;(", ch$df1, ") = ", fmt(ch$stat, 2)), flag(fmt_p(ch$p), gt(ch$p, 0.05 - 1e-12)), fmt(sm$aic, 2))
  })
  a(html_table(if (lin) c("Block", "R&sup2;", "Adj. R&sup2;", "&Delta;R&sup2;", "Change test", "p", "AIC") else c("Block", "McFadden R&sup2;", "Nagelkerke R&sup2;", "Change test", "p", "AIC"),
               summ_rows, "Model summary", num_cols = 2:(if (lin) 7 else 6)))
  for (b in res$blocks) {
    rows <- lapply(b$coefficients, function(cf) {
      base <- c(esc(cf$term), fmt(cf$b), fmt(cf$se), if (lin) (if (is.null(cf$beta)) "&ndash;" else fmt(cf$beta)) else NULL, fmt(cf$stat, 2),
                flag(fmt_p(cf$p), cf$term != "(Intercept)" && gt(cf$p, 0.05 - 1e-12)), paste0("[", fmt(cf$ciLower), ", ", fmt(cf$ciUpper), "]"))
      if (!lin) base <- c(base, paste0(fmt(cf$expB), " [", fmt(cf$expLower), ", ", fmt(cf$expUpper), "]"))
      c(base, if (is.null(cf$vif)) "&ndash;" else flag(fmt(cf$vif), !isTRUE(cf$interaction) && gt(cf$vif, 5)))
    })
    hdr <- c("Term", "B", "SE", if (lin) "&beta;", if (lin) "t" else "z", "p", ci, if (!lin) (if (identical(s$family, "binomial")) "Odds ratio [CI]" else "Rate ratio [CI]"), "VIF")
    a(html_table(hdr, rows, paste0("Coefficients, block ", b$block), num_cols = 2:length(hdr)))
  }
  for (sl in res$simpleSlopes) {
    a(html_table(c(paste0(esc(sl$moderator), " at"), "Value", paste0("Slope of ", esc(sl$predictor)), "SE", "p", ci),
                 lapply(sl$points, function(p) c(esc(p$level), fmt(p$moderatorValue), fmt(p$slope), fmt(p$se), fmt_p(p$p), paste0("[", fmt(p$ciLower), ", ", fmt(p$ciUpper), "]"))),
                 paste0("Simple slopes: ", esc(sl$predictor), " &times; ", esc(sl$moderator)), num_cols = 2:6))
  }
  dg <- res$diagnostics
  drows <- list(c("Influential cases (Cook's D &gt; 4/n)", as.character(dg$nInfluential)))
  if (!is.null(dg$breuschPagan)) drows[[length(drows) + 1]] <- c("Breusch&ndash;Pagan", paste0("&chi;&sup2;(", dg$breuschPagan$df, ") = ", fmt(dg$breuschPagan$stat, 2), ", p ", fmt_p(dg$breuschPagan$p)))
  if (!is.null(dg$shapiro)) drows[[length(drows) + 1]] <- c("Shapiro&ndash;Wilk (residuals)", paste0("W = ", fmt(dg$shapiro$stat), ", p ", fmt_p(dg$shapiro$p)))
  if (!is.null(dg$durbinWatson)) drows[[length(drows) + 1]] <- c("Durbin&ndash;Watson (autocorrelation)", paste0("DW = ", fmt(dg$durbinWatson$stat), ", p ", fmt_p(dg$durbinWatson$p)))
  if (!is.null(dg$classification)) drows[[length(drows) + 1]] <- c("Correctly classified (cut-off 0.5)", paste0(fmt(100 * dg$classification$accuracy, 1), "%"))
  if (!is.null(dg$roc)) drows[[length(drows) + 1]] <- c("Area under the ROC curve (AUC)",
    paste0(fmt(dg$roc$auc), if (is.finite(dg$roc$ciLower %||% NA)) paste0(", 95% CI [", fmt(dg$roc$ciLower), ", ", fmt(dg$roc$ciUpper), "] (DeLong)") else ""))
  a(html_table(c("Diagnostic", "Value"), drows, "Diagnostics (final block)", num_cols = 2))
  a("<h3>R code</h3><pre><code>", esc(res$rCode %||% ""), "</code></pre>")
  paste(S, collapse = "\n")
}

reg_sheets <- function(res, project_name) {
  s <- res$spec
  coefs <- do.call(rbind, lapply(res$blocks, function(b) do.call(rbind, lapply(b$coefficients, function(cf) data.frame(
    Block = b$block, Term = cf$term, B = cf$b, SE = cf$se, Beta = num_of(cf$beta), Statistic = cf$stat, p = cf$p,
    CILower = cf$ciLower, CIUpper = cf$ciUpper, ExpB = num_of(cf$expB), VIF = num_of(cf$vif), stringsAsFactors = FALSE)))))
  summ <- do.call(rbind, lapply(res$blocks, function(b) {
    sm <- b$summary
    data.frame(Block = b$block, Added = paste(ul(b$added), collapse = ", "), R2 = num_of(sm$r2), AdjR2 = num_of(sm$adjR2), DeltaR2 = num_of(sm$deltaR2),
               McFaddenR2 = num_of(sm$mcfaddenR2), NagelkerkeR2 = num_of(sm$nagelkerkeR2), ChangeTest = b$change$test, ChangeStatistic = b$change$stat,
               ChangeDf1 = b$change$df1, ChangeDf2 = num_of(b$change$df2), ChangeP = b$change$p, AIC = sm$aic, BIC = sm$bic, stringsAsFactors = FALSE)
  }))
  out <- list(
    Info = data.frame(Item = c("Project", "Completed (UTC)", "PathLab SEM version", "Model", "Outcome", "Standard errors", "Confidence level", "Rows used", "Rows in dataset"),
                      Value = c(project_name, res$completedAt, PATHLAB_VERSION, res$familyLabel, s$outcome, s$robust, s$ciLevel, res$n$used, res$n$input), stringsAsFactors = FALSE),
    ModelSummary = summ, Coefficients = coefs,
    InfluentialCases = do.call(rbind, lapply(res$diagnostics$influential, function(i) data.frame(Row = i$row, CooksD = i$cooksDistance, Leverage = i$leverage, StdResidual = i$stdResidual)))
  )
  if (length(res$simpleSlopes)) out$SimpleSlopes <- do.call(rbind, lapply(res$simpleSlopes, function(sl) do.call(rbind, lapply(sl$points, function(p) data.frame(
    Predictor = sl$predictor, Moderator = sl$moderator, Level = p$level, ModeratorValue = p$moderatorValue, Slope = p$slope, SE = p$se, p = p$p,
    CILower = p$ciLower, CIUpper = p$ciUpper, stringsAsFactors = FALSE)))))
  out
}

reg_pub_spec <- function(res, opts) {
  d <- opts$decimals; lz <- opts$leadingZero; stars <- identical(opts$pStyle, "stars")
  s <- res$spec; lin <- reg_is_lin(res)
  ci <- sprintf("%d%% CI", round(100 * s$ciLevel))
  hdr <- if (lin) c("Variable", "B", "SE", "β", "t", "p", ci) else c("Variable", "B", "SE", "z", "p", if (identical(s$family, "binomial")) "OR" else "IRR", ci)
  rows <- list(); bold <- list(); span <- integer(0)
  for (b in res$blocks) {
    rows[[length(rows) + 1]] <- c(sprintf("Block %d", b$block), rep("", length(hdr) - 1))
    bold[[length(bold) + 1]] <- c(length(rows), 1)
    for (cf in b$coefficients) {
      if (cf$term == "(Intercept)" && b$block > 1) next
      p_txt <- pt_p(cf$p, lz)
      est <- paste0(pt_num(cf$b, d), if (stars && cf$term != "(Intercept)") pt_stars(cf$p) else "")
      rows[[length(rows) + 1]] <- if (lin) c(cf$term, est, pt_num(cf$se, d), if (is.null(cf$beta)) "" else pt_num(cf$beta, d), pt_num(cf$stat, 2), p_txt, pt_ci(cf$ciLower, cf$ciUpper, d))
        else c(cf$term, est, pt_num(cf$se, d), pt_num(cf$stat, 2), p_txt, pt_num(cf$expB, d), pt_ci(cf$expLower, cf$expUpper, d))
    }
    sm <- b$summary; ch <- b$change
    fit_txt <- if (lin) sprintf("R² = %s, ΔR² = %s, F(%d, %d) = %s, p %s", pt_num(sm$r2, d, TRUE, lz), pt_num(sm$deltaR2, d, TRUE, lz),
                                as.integer(ch$df1), as.integer(ch$df2), pt_num(ch$stat, 2), if (ch$p < 0.001) "< .001" else paste("=", pt_p(ch$p, lz)))
      else sprintf("%s = %s, χ²(%d) = %s, p %s", if (identical(s$family, "binomial")) "Nagelkerke R²" else "McFadden R²",
                   pt_num(if (identical(s$family, "binomial")) sm$nagelkerkeR2 else sm$mcfaddenR2, d, TRUE, lz), as.integer(ch$df1), pt_num(ch$stat, 2),
                   if (ch$p < 0.001) "< .001" else paste("=", pt_p(ch$p, lz)))
    rows[[length(rows) + 1]] <- c(fit_txt, rep("", length(hdr) - 1))
    span <- c(span, length(rows))
  }
  notes <- list(paste0(sprintf("N = %d. Outcome: %s. ", res$n$used, s$outcome),
                       if (s$robust != "none") sprintf("%s heteroscedasticity-consistent standard errors. ", s$robust) else "",
                       if (length(res$centred)) sprintf("Variables in interactions were mean-centred (%s). ", paste(vapply(res$centred, `[[`, "", "variable"), collapse = ", ")) else "",
                       if (!is.null(res$event)) sprintf("Event coded 1: %s = %s. ", s$outcome, res$event$level) else "",
                       if (lin) "ΔR² and the F test compare each block with the previous one." else "Change tests compare each block with the previous one."))
  if (stars) notes[[2]] <- if (identical(lz, "apa")) "*p < .05. **p < .01. ***p < .001." else "*p < 0.05. **p < 0.01. ***p < 0.001."
  title <- sprintf("%s Regression Predicting %s", if (length(res$blocks) > 1) "Hierarchical" else tools::toTitleCase(sub(" \\(OLS\\)", "", res$familyLabel)), s$outcome)
  if (length(res$blocks) > 1 && !lin) title <- sprintf("Hierarchical %s Regression Predicting %s", res$familyLabel, s$outcome)
  tabs <- list(pt_table("reg_coefficients", title, hdr, rows, notes = notes, bold = bold, span = span))
  if (length(res$simpleSlopes)) {
    srows <- do.call(c, lapply(res$simpleSlopes, function(sl) lapply(sl$points, function(p) c(sprintf("%s at %s %s", sl$predictor, sl$moderator, p$level),
      pt_num(p$moderatorValue, d), pt_num(p$slope, d), pt_num(p$se, d), pt_p(p$p, lz), pt_ci(p$ciLower, p$ciUpper, d)))))
    tabs[[2]] <- pt_table("reg_slopes", "Simple Slopes", c("Effect", "Moderator value", "Slope", "SE", "p", ci), srows,
                          notes = list("Slopes at the moderator's mean − 1 SD, mean and mean + 1 SD (final model)."))
  }
  tabs <- Filter(Negate(is.null), tabs)
  for (i in seq_along(tabs)) tabs[[i]]$number <- i
  tabs
}

