# Reports, workbooks and APA tables for the analyses besides PLS-SEM (EFA/PCA and regression), plus the
# combined report of several analyses. Results are stored server-side like PLS results (result JSON on disk),
# tagged with `kind`, so every export reads the numbers R produced; the browser never supplies them.

#' Store a synchronous result (EFA, regression) and return it with its id.
store_result <- function(proj, kind, res, dataset_id) {
  id <- new_id("r")
  res$id <- id
  res$kind <- kind
  res$datasetId <- dataset_id
  res$completedAt <- now_iso()
  dir <- file.path(proj$dir, "results")
  dir.create(dir, recursive = TRUE, showWarnings = FALSE)
  path <- file.path(dir, paste0(id, ".json"))
  res <- save_result_derived(res, path)
  writeLines(jsonlite::toJSON(res, auto_unbox = TRUE, null = "null", na = "null", digits = NA), path, useBytes = TRUE)
  proj$results[[id]] <- path
  res
}

