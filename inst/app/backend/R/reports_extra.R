ul <- function(x) unlist(x, use.names = FALSE)

# ---- EFA / PCA ------------------------------------------------------------------------------------------

efa_sorted_rows <- function(res) {
  facs <- ul(res$factors)
  items <- setNames(res$items, vapply(res$items, `[[`, "", "variable"))
  ord <- order(match(vapply(res$loadings, function(l) items[[l$variable]]$factor, ""), facs),
               -vapply(res$loadings, function(l) abs(items[[l$variable]]$loading), 0))
  lapply(res$loadings[ord], function(l) list(row = l, item = items[[l$variable]]))
}

efa_body_html <- function(res) {
  esc <- html_escape
  o <- res$options
  facs <- ul(res$factors)
  kind <- if (identical(res$eigen$kind, "components")) "component" else "factor"
  S <- character(0); a <- function(...) S <<- c(S, paste0(...))
  a("<h2>Exploratory factor analysis</h2>")
  a("<p>", esc(res$methodLabel), " with ", if (identical(res$rotationApplied, "none")) "no rotation" else paste0(esc(res$rotationApplied), " rotation"),
    " on ", esc(o$cor), " correlations of ", length(ul(o$variables)), " variables (n = ", res$n$used,
    if (isTRUE(o$split$enabled)) paste0(", random half ", o$split$half, " of ", res$n$input, " rows, seed ", o$seed) else "",
    if (res$n$rowsRemoved > 0) paste0("; ", res$n$rowsRemoved, " row(s) with missing values removed listwise") else "",
    "). Estimated with the psych package ", esc(res$psychVersion), ".</p>")
  a(html_table(c("Statistic", "Value"), list(
    c("Kaiser&ndash;Meyer&ndash;Olkin (KMO)", flag(fmt(res$kmo$overall), lt(res$kmo$overall, 0.6))),
    c("Bartlett's test of sphericity", paste0("&chi;&sup2;(", res$bartlett$df, ") = ", fmt(res$bartlett$chisq, 2), ", p ", if (res$bartlett$p < 0.001) "&lt; 0.001" else paste("=", fmt(res$bartlett$p)))),
    c(paste0("Retained ", kind, "s"), paste0(res$nfactors, " (parallel analysis suggests ", res$suggested$parallel %||% "&ndash;", "; eigenvalue &gt; 1 suggests ", res$suggested$kaiser, ")"))
  ), "Sampling adequacy and number of factors", num_cols = 2))
  for (w in ul(res$warnings)) a("<div class=\"warn\">", esc(w), "</div>")
  rows <- lapply(efa_sorted_rows(res), function(x) {
    c(esc(x$row$variable), vapply(facs, function(f) {
      v <- as.numeric(x$row[[f]])
      if (abs(v) < o$cutoff) "" else if (identical(x$item$factor, f)) paste0("<strong>", fmt(v), "</strong>") else flag(fmt(v), TRUE)
    }, ""), flag(fmt(x$item$communality), lt(x$item$communality, 0.4)))
  })
  a(html_table(c("Variable", esc(facs), "h&sup2;"), rows,
               sprintf("%s loadings (values below %.2f omitted; bold = primary loading; red = cross-loading or low communality)", if (kind == "component") "Component" else "Pattern", o$cutoff),
               num_cols = 2:(length(facs) + 2)))
  a(html_table(c(if (kind == "component") "Component" else "Factor", "SS loadings", "% of variance", "Cumulative %"),
               lapply(res$variance, function(v) c(esc(v$factor), fmt(v$ssLoadings), fmt(100 * v$proportion, 1), fmt(100 * v$cumulative, 1))),
               "Variance explained", num_cols = 2:4))
  if (!is.null(res$phi)) a(html_table(c("", esc(facs)), lapply(res$phi, function(r) c(esc(r$factor), vapply(facs, function(f) fmt(r[[f]]), ""))),
                                      "Factor correlations", num_cols = seq_along(facs) + 1))
  flagged <- Filter(function(i) isTRUE(i$belowCutoff) || isTRUE(i$crossLoading), res$items)
  if (length(flagged)) a("<p class=\"note\">Flagged items: ", esc(paste(vapply(flagged, function(i) paste0(i$variable, if (isTRUE(i$belowCutoff)) " (below cut-off)" else " (cross-loading)"), ""), collapse = ", ")), ".</p>")
  a("<p class=\"note\">Exploring and confirming a factor structure on the same respondents capitalises on chance; ",
    if (isTRUE(o$split$enabled)) "this EFA used one random half of the sample." else "consider a split-sample design.", "</p>")
  a("<h3>R code</h3><pre><code>", esc(res$rCode %||% ""), "</code></pre>")
  paste(S, collapse = "\n")
}

efa_sheets <- function(res, project_name) {
  facs <- ul(res$factors)
  load <- do.call(rbind, lapply(efa_sorted_rows(res), function(x) {
    d <- data.frame(Variable = x$row$variable, stringsAsFactors = FALSE)
    for (f in facs) d[[f]] <- as.numeric(x$row[[f]])
    d$Communality <- x$item$communality; d$PrimaryFactor <- x$item$factor
    d$BelowCutoff <- isTRUE(x$item$belowCutoff); d$CrossLoading <- isTRUE(x$item$crossLoading)
    d
  }))
  out <- list(
    Info = data.frame(Item = c("Project", "Completed (UTC)", "PathLab SEM version", "psych version", "Method", "Rotation", "Correlations",
                               "Rows used", "Rows in dataset", "KMO", "Bartlett chi-square", "Bartlett df", "Bartlett p", "Factors retained",
                               "Parallel analysis suggests", "Eigenvalue > 1 suggests"),
                      Value = c(project_name, res$completedAt, PATHLAB_VERSION, res$psychVersion, res$methodLabel, res$rotationApplied, res$options$cor,
                                res$n$used, res$n$input, res$kmo$overall, res$bartlett$chisq, res$bartlett$df, res$bartlett$p, res$nfactors,
                                res$suggested$parallel %||% NA, res$suggested$kaiser), stringsAsFactors = FALSE),
    Loadings = load,
    Variance = data.frame(Factor = vapply(res$variance, `[[`, "", "factor"), SSLoadings = vapply(res$variance, function(v) v$ssLoadings, 0),
                          Proportion = vapply(res$variance, function(v) v$proportion, 0), Cumulative = vapply(res$variance, function(v) v$cumulative, 0)),
    ItemMSA = data.frame(Variable = vapply(res$kmo$items, `[[`, "", "variable"), MSA = vapply(res$kmo$items, function(i) i$msa, 0)),
    Eigenvalues = data.frame(Number = seq_along(ul(res$eigen$observed)), Observed = as.numeric(ul(res$eigen$observed)),
                             RandomData = vapply(res$eigen$simulated, function(v) if (is.null(v)) NA_real_ else as.numeric(v), 0))
  )
  if (!is.null(res$phi)) {
    ph <- data.frame(Factor = vapply(res$phi, `[[`, "", "factor"))
    for (f in facs) ph[[f]] <- vapply(res$phi, function(r) as.numeric(r[[f]]), 0)
    out$FactorCorrelations <- ph
  }
  out
}

efa_pub_spec <- function(res, opts) {
  d <- opts$decimals; lz <- opts$leadingZero
  o <- res$options
  facs <- ul(res$factors)
  kind <- if (identical(res$eigen$kind, "components")) "Component" else "Factor"
  rows <- list(); bold <- list()
  for (x in efa_sorted_rows(res)) {
    vals <- vapply(facs, function(f) { v <- as.numeric(x$row[[f]]); if (abs(v) < o$cutoff) "" else pt_num(v, d, TRUE, lz) }, "")
    rows[[length(rows) + 1]] <- c(x$row$variable, vals, pt_num(x$item$communality, d, TRUE, lz))
    bold[[length(bold) + 1]] <- c(length(rows), 1 + match(x$item$factor, facs))
  }
  rows[[length(rows) + 1]] <- c("Eigenvalue (SS loadings)", vapply(res$variance, function(v) pt_num(v$ssLoadings, 2), ""), "")
  rows[[length(rows) + 1]] <- c("% of variance", vapply(res$variance, function(v) formatC(100 * v$proportion, format = "f", digits = 1), ""), "")
  bart_p <- if (res$bartlett$p < 0.001) "< .001" else paste("=", pt_p(res$bartlett$p, lz))
  note <- sprintf("N = %d. %s with %s%s; %s correlations. Loadings below %s are omitted; the highest loading of each item is in bold. KMO = %s; Bartlett's test χ²(%d) = %s, p %s. Number of %ss from %s.",
                  res$n$used, res$methodLabel, if (identical(res$rotationApplied, "none")) "no rotation" else paste(res$rotationApplied, "rotation"),
                  if (isTRUE(o$split$enabled)) sprintf(" (random half %d of the sample, seed %s)", o$split$half, o$seed) else "",
                  if (identical(o$cor, "polychoric")) "polychoric" else "Pearson", pt_num(o$cutoff, 2, TRUE, lz),
                  pt_num(res$kmo$overall, 2, TRUE, lz), as.integer(res$bartlett$df), pt_num(res$bartlett$chisq, 2), bart_p, tolower(kind),
                  switch(o$nfactorsRule, parallel = "parallel analysis", kaiser = "the eigenvalue > 1 rule", fixed = "a fixed choice"))
  tabs <- list(pt_table("efa_loadings", sprintf("Exploratory %s Analysis: %s Loadings", if (kind == "Component") "Principal Component" else "Factor",
                                                  if (kind == "Component" || !(res$rotationApplied %in% c("oblimin", "promax"))) kind else "Pattern"),
                        c("Item", facs, "h²"), rows, notes = list(note), bold = bold))
  if (!is.null(res$phi)) {
    prow <- lapply(seq_along(res$phi), function(i) { r <- res$phi[[i]]; c(r$factor, vapply(seq_along(facs), function(j) if (j > i) "" else if (j == i) "—" else pt_num(as.numeric(r[[facs[j]]]), d, TRUE, lz), "")) })
    tabs[[2]] <- pt_table("efa_phi", "Factor Correlations", c("Factor", facs), prow, notes = list(sprintf("%s rotation.", tools::toTitleCase(res$rotationApplied))))
  }
  tabs <- Filter(Negate(is.null), tabs)
  for (i in seq_along(tabs)) tabs[[i]]$number <- i
  tabs
}

