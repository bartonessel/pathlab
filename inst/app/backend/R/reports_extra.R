#' Body (between <body> and </body>, without the footer) of a full report document.
report_body <- function(html) {
  b <- sub("(?s)^.*?<body>", "", html, perl = TRUE)
  b <- sub("(?s)</body>.*$", "", b, perl = TRUE)
  sub("(?s)<footer>.*?</footer>", "", b, perl = TRUE)
}

#' One report of several analyses. `items`: list of list(result, title, svg, decisionRule).
combined_report_html <- function(items, project_name, ds_of) {
  toc <- paste0("<ol>", paste(vapply(seq_along(items), function(i) sprintf("<li><a href=\"#analysis-%d\">%s</a></li>", i, html_escape(items[[i]]$title)), ""), collapse = ""), "</ol>")
  parts <- vapply(seq_along(items), function(i) {
    it <- items[[i]]
